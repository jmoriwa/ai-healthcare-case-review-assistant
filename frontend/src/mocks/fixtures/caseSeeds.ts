import type { CaseStatus, ProcedureType } from "@/domain/enums";
import type { PatientSummary } from "@/domain/models";

export interface CaseSeed {
  id: string;
  caseNumber: string;
  patient: PatientSummary;
  procedureType: ProcedureType;
  status: CaseStatus;
  assignedReviewerId: string | null;
  createdAt: string;
  updatedAt: string;
  analysisVersions: number;
  /** Index into the criterion-status pattern table used to shape assessments. */
  pattern: 0 | 1 | 2;
}

function patient(
  index: number,
  displayName: string,
  birthDate: string,
  sex: PatientSummary["sex"],
): PatientSummary {
  const padded = String(index).padStart(4, "0");
  return {
    id: `pat-${padded}`,
    displayName,
    birthDate,
    sex,
    fhirPatientId: `synthetic-patient-${padded}`,
  };
}

function iso(day: number, hour: number): string {
  const date = new Date(Date.UTC(2026, 6, day, hour, 15, 0));
  return date.toISOString();
}

